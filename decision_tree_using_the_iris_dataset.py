import pandas as pd
import sklearn.datasets as datas
from sklearn import tree
from sklearn.model_selection import train_test_split

import sklearn.datasets as datas
irisdata=datas.load_iris()
irisdata

irisdata.keys()

irisdata.target_names

irisdata.target

irisInData=irisdata.data

irisInData=pd.DataFrame(irisdata.data)
irisInData.head()

irisInData.columns=['sepal length','sepal width','petal length','petal width']
irisInData.head()

irisIndTrain,irisIndTest,irisDepTrain,irisDepTest=train_test_split(irisInData,irisdata.target,test_size=0.2,random_state=0)
dt=tree.DecisionTreeClassifier(max_depth=4,criterion="entropy")
mod1=dt.fit(irisIndTrain,irisDepTrain)
predictedData=mod1.predict(irisIndTest)
predictedData

import graphviz
dot_data=tree.export_graphviz(dt,out_file=None,feature_names=irisdata.feature_names,class_names=irisdata.target_names,filled=True,rounded=True,special_characters=True)
graph=graphviz.Source(dot_data)
